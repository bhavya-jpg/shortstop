// Writes data/synthetic/postgres-seed.sql from the synthetic JSON files, so the
// same SYNTHETIC hospital data can be served to Zetaris from PostgreSQL.
//   npm run data:postgres-seed
//   psql -d shortstop_synthetic -f data/synthetic/postgres-seed.sql
// Column names match what ZetarisDataSource selects.

import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "data", "synthetic");
const read = (f: string) => (JSON.parse(fs.readFileSync(path.join(dir, f), "utf-8")) as { records: Record<string, unknown>[] }).records;

const lit = (v: unknown): string => {
  if (v === undefined || v === null) return "NULL";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "NULL";
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  return `'${String(v).replace(/'/g, "''")}'`;
};

const tables: { name: string; ddl: string; cols: string[]; rows: Record<string, unknown>[] }[] = [
  {
    name: "formulary",
    ddl: "item_id TEXT PRIMARY KEY, ndc TEXT NOT NULL, generic_name TEXT, description TEXT, dosage_form TEXT, strength TEXT, package_description TEXT, status TEXT NOT NULL, synthetic BOOLEAN NOT NULL",
    cols: ["item_id", "ndc", "generic_name", "description", "dosage_form", "strength", "package_description", "status", "synthetic"],
    rows: read("formulary.json"),
  },
  {
    name: "inventory",
    ddl: "item_id TEXT NOT NULL, location_id TEXT NOT NULL, on_hand_units NUMERIC NOT NULL, unit TEXT, as_of DATE NOT NULL, synthetic BOOLEAN NOT NULL",
    cols: ["item_id", "location_id", "on_hand_units", "unit", "as_of", "synthetic"],
    rows: read("inventory.json"),
  },
  {
    name: "usage",
    ddl: "item_id TEXT NOT NULL, location_id TEXT NOT NULL, usage_date DATE NOT NULL, units_used NUMERIC NOT NULL, synthetic BOOLEAN NOT NULL",
    cols: ["item_id", "location_id", "usage_date", "units_used", "synthetic"],
    rows: read("usage.json").map((r) => ({ ...r, usage_date: r.date })),
  },
  {
    name: "policies",
    ddl: "policy_id TEXT PRIMARY KEY, action TEXT NOT NULL, applies_to_item_id TEXT NOT NULL, target_item_id TEXT, trigger_max_days_on_hand NUMERIC NOT NULL, requirements TEXT, approved_by TEXT, effective_date DATE NOT NULL, expires_date DATE, status TEXT NOT NULL, synthetic BOOLEAN NOT NULL",
    cols: ["policy_id", "action", "applies_to_item_id", "target_item_id", "trigger_max_days_on_hand", "requirements", "approved_by", "effective_date", "expires_date", "status", "synthetic"],
    rows: read("policies.json"),
  },
];

const out: string[] = [
  "-- SYNTHETIC hospital data for the ShortStop demonstration. Generated by scripts/generate-postgres-seed.ts.",
  "-- Not a real hospital, not real stock or usage, not real policy. Do not edit by hand.",
  "BEGIN;",
];
for (const t of tables) {
  out.push(`DROP TABLE IF EXISTS ${t.name};`, `CREATE TABLE ${t.name} (${t.ddl});`);
  out.push(`COMMENT ON TABLE ${t.name} IS 'SYNTHETIC demonstration data (ShortStop)';`);
  for (const r of t.rows) out.push(`INSERT INTO ${t.name} (${t.cols.join(", ")}) VALUES (${t.cols.map((c) => lit(r[c])).join(", ")});`);
}
out.push("COMMIT;");
fs.writeFileSync(path.join(dir, "postgres-seed.sql"), out.join("\n") + "\n");
console.log(`wrote data/synthetic/postgres-seed.sql (${tables.map((t) => `${t.name}=${t.rows.length}`).join(", ")})`);
