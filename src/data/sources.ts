import type { ZetarisConfig } from "../config.ts";
import { addDays, parseDate } from "../domain/dates.ts";
import { normalizeNdc } from "../domain/ndc.ts";
import { normalizeShortage } from "../domain/shortage.ts";
import type {
  FormularyItem,
  HospitalData,
  InventoryRecord,
  Mode,
  PolicyRecord,
  ShortageRecord,
  UsageRecord,
} from "../domain/types.ts";
import { POLICY_ACTIONS } from "../domain/types.ts";
import type { Tracer } from "../trace/tracer.ts";

export class DataSourceError extends Error {
  override name = "DataSourceError";
}

export interface ShortageLookup {
  records: ShortageRecord[];
  source_detail: string;
  fetched_at: string | null;
}

export interface DataSource {
  readonly name: string;
  readonly mode: Mode;
  loadHospital(opts: { asOf: string; usageWindowDays: number }): Promise<HospitalData>;
  // NDCs as the hospital records them; the source handles the openFDA format.
  loadShortages(ndcs: readonly string[]): Promise<ShortageLookup>;
}

const repoRoot = path.resolve(import.meta.dirname, "..", "..");

// ---------------------------------------------------------------- sample mode

interface SyntheticFile<T> {
  synthetic: boolean;
  notice: string;
  records: T[];
}

export class SampleDataSource implements DataSource {
  readonly name = "sample-files";
  readonly mode = "sample" as const;
  constructor(private readonly dataDir = path.join(repoRoot, "data")) {}

  private readSynthetic<T extends { synthetic?: unknown }>(file: string): T[] {
    const full = path.join(this.dataDir, "synthetic", file);
    const body = JSON.parse(fs.readFileSync(full, "utf-8")) as SyntheticFile<T>;
    if (body.synthetic !== true || !body.records.every((r) => r.synthetic === true)) {
      throw new DataSourceError(`${full} is not fully labelled synthetic; refusing to use it as sample hospital data`);
    }
    return body.records;
  }

  async loadHospital(): Promise<HospitalData> {
    return {
      formulary: this.readSynthetic<FormularyItem>("formulary.json"),
      locations: this.readSynthetic("locations.json"),
      inventory: this.readSynthetic<InventoryRecord>("inventory.json"),
      usage: this.readSynthetic<UsageRecord>("usage.json"),
      policies: this.readSynthetic<PolicyRecord>("policies.json"),
      provenance: { dataset: "data/synthetic (generated by scripts/generate-synthetic.ts)", synthetic: true, retrieved_via: "sample-file" },
    };
  }

  async loadShortages(ndcs: readonly string[]): Promise<ShortageLookup> {
    const snap = JSON.parse(fs.readFileSync(path.join(this.dataDir, "openfda", "shortages-snapshot.json"), "utf-8")) as {
      fetched_at: string;
      results: unknown[];
    };
    const wanted = new Set(ndcs.map((n) => normalizeNdc(n)).flatMap((n) => (n.ok ? [n.ndc11] : [])));
    const prov = { dataset: "openFDA drug shortages (snapshot)", synthetic: false, retrieved_via: "sample-file" as const, detail: `data/openfda/shortages-snapshot.json fetched ${snap.fetched_at}` };
    const records = snap.results.map((r) => normalizeShortage(r, prov)).filter((r) => r.package_ndc !== null && wanted.has(r.package_ndc));
    return { records, source_detail: prov.detail, fetched_at: snap.fetched_at };
  }
}

// ------------------------------------------------------------------ live mode

// Non-numeric values become NaN; the exposure calculation excludes them with an explanation.
const num = (v: unknown): number =>
  typeof v === "number" ? v : typeof v === "string" && v.trim() !== "" ? Number(v) : Number.NaN;
const text = (v: unknown): string => (v === null || v === undefined ? "" : String(v));
const isoDate = (v: unknown): string => {
  const s = text(v);
  return parseDate(s.slice(0, 10)) ?? s;
};
const bool = (v: unknown): boolean => v === true || v === "true" || v === 1 || v === "t";

export class ZetarisDataSource implements DataSource {
  readonly name = "zetaris";
  readonly mode = "live" as const;
  readonly client: ZetarisClient;

  constructor(private readonly cfg: ZetarisConfig, tracer: Tracer, client?: ZetarisClient) {
    this.client = client ?? new ZetarisClient(cfg);
    this.client.onCall = (c) =>
      tracer.emit({
        stage: "RETRIEVE_DATA",
        agent: "ZetarisAdapter",
        action: "sql_request",
        status: c.error || (c.httpStatus ?? 0) >= 400 ? "failure" : "success",
        summary: c.error ? `request failed: ${c.error}` : `HTTP ${c.httpStatus} in ${c.durationMs} ms`,
        external: { service: "zetaris", endpoint: c.endpoint, attempts: c.attempt, duration_ms: c.durationMs, ...(c.httpStatus ? { http_status: c.httpStatus } : {}) },
        details: { query_id: c.queryId, request_id: c.requestId },
      });
  }

  private async select<T extends string>(table: string, columns: readonly T[], where = ""): Promise<Record<T, unknown>[]> {
    const sql = `SELECT ${columns.join(", ")} FROM ${table}${where ? ` WHERE ${where}` : ""}`;
    const r = await this.client.query(sql, columns);
    return r.rows;
  }

  async loadHospital(opts: { asOf: string; usageWindowDays: number }): Promise<HospitalData> {
    const t = this.cfg.tables;
    const since = addDays(opts.asOf, -opts.usageWindowDays - 1);
    const [f, inv, use, pol] = [
      await this.select(t.formulary, ["item_id", "ndc", "generic_name", "description", "dosage_form", "strength", "package_description", "status", "synthetic"] as const),
      await this.select(t.inventory, ["item_id", "location_id", "on_hand_units", "unit", "as_of", "synthetic"] as const),
      await this.select(t.usage, ["item_id", "location_id", "usage_date", "units_used", "synthetic"] as const, `usage_date >= '${since}'`),
      await this.select(t.policies, ["policy_id", "action", "applies_to_item_id", "target_item_id", "trigger_max_days_on_hand", "requirements", "approved_by", "effective_date", "expires_date", "status", "synthetic"] as const),
    ];
    const formulary: FormularyItem[] = f.map((r) => ({
      item_id: text(r.item_id), ndc: text(r.ndc), generic_name: text(r.generic_name), description: text(r.description),
      dosage_form: text(r.dosage_form), strength: text(r.strength), package_description: text(r.package_description),
      status: text(r.status) === "active" ? "active" : "inactive", synthetic: bool(r.synthetic),
    }));
    const inventory: InventoryRecord[] = inv.map((r) => ({
      item_id: text(r.item_id), location_id: text(r.location_id), on_hand_units: num(r.on_hand_units),
      unit: text(r.unit), as_of: isoDate(r.as_of), synthetic: bool(r.synthetic),
    }));
    const usage: UsageRecord[] = use.map((r) => ({
      item_id: text(r.item_id), location_id: text(r.location_id), date: isoDate(r.usage_date),
      units_used: num(r.units_used), synthetic: bool(r.synthetic),
    }));
    const policies: PolicyRecord[] = pol.flatMap((r) => {
      const action = text(r.action);
      if (!(POLICY_ACTIONS as readonly string[]).includes(action)) return []; // unknown action types are never usable
      const p: PolicyRecord = {
        policy_id: text(r.policy_id), action: action as PolicyRecord["action"], applies_to_item_id: text(r.applies_to_item_id),
        trigger_max_days_on_hand: num(r.trigger_max_days_on_hand), requirements: text(r.requirements),
        approved_by: text(r.approved_by), effective_date: isoDate(r.effective_date),
        status: text(r.status) === "active" ? "active" : "retired", synthetic: bool(r.synthetic),
      };
      if (text(r.target_item_id)) p.target_item_id = text(r.target_item_id);
      if (text(r.expires_date)) p.expires_date = isoDate(r.expires_date);
      return [p];
    });
    const allSynthetic = [...formulary, ...inventory, ...usage, ...policies].every((r) => r.synthetic);
    return {
      formulary, locations: [], inventory, usage, policies,
      provenance: {
        dataset: `hospital tables ${t.formulary}, ${t.inventory}, ${t.usage}, ${t.policies}`,
        synthetic: allSynthetic,
        retrieved_via: "zetaris",
        detail: allSynthetic ? "rows are flagged synthetic in the source tables" : "WARNING: some rows are not flagged synthetic",
      },
    };
  }

  async loadShortages(ndcs: readonly string[]): Promise<ShortageLookup> {
    // NDCs are validated digits-and-hyphens before they reach SQL.
    const valid = ndcs.filter((n) => /^\d{4,5}-\d{3,4}-\d{1,2}$/.test(n));
    if (valid.length === 0) return { records: [], source_detail: "no valid NDCs to look up", fetched_at: null };
    const cols = ["package_ndc", "generic_name", "presentation", "company_name", "dosage_form", "status", "availability", "shortage_reason", "update_date", "initial_posting_date", "rxcui", "has_openfda_block"] as const;
    const rows = await this.select(this.cfg.tables.shortages, cols, `package_ndc IN (${valid.map((n) => `'${n}'`).join(", ")})`);
    const prov = { dataset: "openFDA drug shortages", synthetic: false, retrieved_via: "zetaris" as const, detail: `Zetaris table ${this.cfg.tables.shortages}` };
    return { records: rows.map((r) => normalizeShortage(r, prov)), source_detail: prov.detail, fetched_at: new Date().toISOString() };
  }
}
