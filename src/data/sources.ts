// Data sources. Both return the same typed records, so the workflow, exposure
// math and validators are identical in sample and live mode.
//   SampleDataSource  - bundled files: real openFDA snapshot + synthetic hospital data
//   ZetarisDataSource - SQL through the Zetaris REST API; no fallback to files

import fs from "node:fs";
import path from "node:path";
